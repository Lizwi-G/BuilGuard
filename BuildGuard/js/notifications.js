/*
  notifications.js — the bell icon panel. Notifications are generated by
  db.js on key events (approval required, approved/rejected, new money
  leak) and already targeted to the right recipients/roles there — this
  module is purely presentation.
*/

import { getSession } from './state.js';
import { listNotifications, markNotificationRead, markAllNotificationsRead } from './db.js';
import { escapeHtml, timeAgo, openModal, closeModal } from './utils.js';

const TYPE_ICON = {
  approval_required: '📥', request_approved: '✅', request_rejected: '🚫',
  info_requested: '❓', money_leak: '💸', delivery_shortage: '🚚'
};

export function setupNotificationPanel(onBadgeChange) {
  const btn = document.getElementById('notifBtn');
  if (!btn) return;
  btn.addEventListener('click', () => openPanel(onBadgeChange));
}

function openPanel(onBadgeChange) {
  const session = getSession();
  if (!session) return;
  const notifs = listNotifications(session.userId).slice(0, 30);

  const card = openModal(`
    <div class="flex justify-between items-center mb-2">
      <h3 style="margin:0">Notifications</h3>
      <button class="btn btn-ghost btn-sm" id="markAllBtn">Mark all read</button>
    </div>
    <div class="notif-panel">
      ${notifs.length ? notifs.map(notifRow).join('') : '<div class="empty-state"><div class="emoji">🔔</div>No notifications yet.</div>'}
    </div>
    <button class="btn btn-ghost w-full mt-3" id="closeBtn">Close</button>
  `);

  card.querySelectorAll('[data-notif]').forEach((el) => {
    el.addEventListener('click', () => {
      markNotificationRead(el.dataset.notif);
      const route = el.dataset.route;
      closeModal();
      onBadgeChange && onBadgeChange();
      if (route) location.hash = route;
    });
  });
  card.querySelector('#markAllBtn').addEventListener('click', () => {
    markAllNotificationsRead(session.userId);
    onBadgeChange && onBadgeChange();
    closeModal();
  });
  card.querySelector('#closeBtn').addEventListener('click', closeModal);
}

function notifRow(n) {
  const route = n.entity_type === 'request' ? '#/approvals' : n.entity_type === 'alert' ? '#/moneyleaks' : n.entity_type === 'delivery' ? '#/deliveries' : '';
  return `
    <div class="notif-item ${n.read ? '' : 'unread'}" data-notif="${n.id}" data-route="${route}" style="cursor:pointer;">
      <div class="flex gap-2 items-center">
        <span>${TYPE_ICON[n.type] || '🔔'}</span>
        <div style="flex:1;min-width:0;">
          <div style="font-weight:700;font-size:13.5px;">${escapeHtml(n.title)}</div>
          <div class="faint">${escapeHtml(n.message)}</div>
          <div class="faint">${timeAgo(n.created_at)}</div>
        </div>
        ${n.read ? '' : '<span class="badge badge-info">new</span>'}
      </div>
    </div>`;
}
